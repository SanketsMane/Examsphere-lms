import "server-only";

import { createReadStream } from "node:fs";
import { mkdir, readFile, rm, stat, writeFile, rename } from "node:fs/promises";
import path from "node:path";
import { Readable } from "node:stream";
import {
  DeleteObjectCommand,
  GetObjectCommand,
  HeadObjectCommand,
  PutObjectCommand,
  S3Client,
} from "@aws-sdk/client-s3";

/**
 * Private file storage for paid / unpublished material (notes PDFs, AI source uploads).
 *
 * Never use the public images bucket for these: it is world-readable, so anyone holding
 * a key could download a paid PDF. Files stored here are only ever streamed back through
 * routes that check the user's access first.
 *
 * Driver is chosen by PRIVATE_STORAGE_DRIVER:
 *   - "local" (default): files on the server's own disk under PRIVATE_STORAGE_DIR.
 *     Keep that directory OUTSIDE the repo and outside any web root in production,
 *     e.g. /var/lib/examsphere/private, and include it in backups.
 *   - "s3": a separate PRIVATE bucket (Cloudflare R2 / S3 / MinIO), configured with
 *     PRIVATE_S3_BUCKET and optional PRIVATE_S3_* credentials (falls back to AWS_*).
 */

export interface PrivateStorage {
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<Buffer>;
  /** Stream for large responses. */
  stream(key: string): Promise<{ body: ReadableStream<Uint8Array>; size?: number }>;
  exists(key: string): Promise<boolean>;
  delete(key: string): Promise<void>;
}

/** Keys are generated by our code, but validate anyway so nothing can escape the root. */
export function assertSafeKey(key: string): string {
  if (
    !key ||
    key.length > 512 ||
    key.startsWith("/") ||
    key.includes("\\") ||
    key.includes("\0") ||
    key.split("/").some((part) => part === "" || part === "." || part === "..") ||
    !/^[A-Za-z0-9._\-/]+$/.test(key)
  ) {
    throw new Error(`Invalid storage key: ${JSON.stringify(key)}`);
  }
  return key;
}

class LocalStorage implements PrivateStorage {
  constructor(private root: string) {}

  private file(key: string) {
    const resolved = path.resolve(this.root, assertSafeKey(key));
    if (!resolved.startsWith(path.resolve(this.root) + path.sep)) {
      throw new Error("Storage key escapes the storage root");
    }
    return resolved;
  }

  async put(key: string, body: Buffer) {
    const target = this.file(key);
    await mkdir(path.dirname(target), { recursive: true, mode: 0o700 });
    // Write-then-rename so a reader never sees a half-written file.
    const tmp = `${target}.${process.pid}.${Date.now()}.tmp`;
    await writeFile(tmp, body, { mode: 0o600 });
    await rename(tmp, target);
  }

  async get(key: string) {
    return readFile(this.file(key));
  }

  async stream(key: string) {
    const target = this.file(key);
    const { size } = await stat(target);
    const body = Readable.toWeb(createReadStream(target)) as ReadableStream<Uint8Array>;
    return { body, size };
  }

  async exists(key: string) {
    try {
      await stat(this.file(key));
      return true;
    } catch {
      return false;
    }
  }

  async delete(key: string) {
    await rm(this.file(key), { force: true });
  }
}

class S3Storage implements PrivateStorage {
  constructor(private client: S3Client, private bucket: string) {}

  async put(key: string, body: Buffer, contentType: string) {
    await this.client.send(
      new PutObjectCommand({ Bucket: this.bucket, Key: assertSafeKey(key), Body: body, ContentType: contentType })
    );
  }

  async get(key: string) {
    const res = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: assertSafeKey(key) }));
    const bytes = await res.Body!.transformToByteArray();
    return Buffer.from(bytes);
  }

  async stream(key: string) {
    const res = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: assertSafeKey(key) }));
    return { body: res.Body!.transformToWebStream() as ReadableStream<Uint8Array>, size: res.ContentLength };
  }

  async exists(key: string) {
    try {
      await this.client.send(new HeadObjectCommand({ Bucket: this.bucket, Key: assertSafeKey(key) }));
      return true;
    } catch (err: any) {
      if (err?.$metadata?.httpStatusCode === 404 || err?.name === "NotFound") return false;
      throw err;
    }
  }

  async delete(key: string) {
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: assertSafeKey(key) }));
  }
}

let instance: PrivateStorage | null = null;

export function getPrivateStorage(): PrivateStorage {
  if (instance) return instance;

  const driver = (process.env.PRIVATE_STORAGE_DRIVER || "local").toLowerCase();
  if (driver === "s3") {
    const bucket = process.env.PRIVATE_S3_BUCKET;
    const accessKeyId = process.env.PRIVATE_S3_ACCESS_KEY_ID || process.env.AWS_ACCESS_KEY_ID;
    const secretAccessKey = process.env.PRIVATE_S3_SECRET_ACCESS_KEY || process.env.AWS_SECRET_ACCESS_KEY;
    const endpoint = process.env.PRIVATE_S3_ENDPOINT || process.env.AWS_ENDPOINT_URL_S3 || undefined;
    if (!bucket || !accessKeyId || !secretAccessKey) {
      throw new Error("PRIVATE_STORAGE_DRIVER=s3 needs PRIVATE_S3_BUCKET and S3 credentials");
    }
    const client = new S3Client({
      region: process.env.PRIVATE_S3_REGION || process.env.AWS_REGION || "auto",
      endpoint,
      forcePathStyle: !!endpoint,
      credentials: { accessKeyId, secretAccessKey },
      requestChecksumCalculation: "WHEN_REQUIRED",
      responseChecksumValidation: "WHEN_REQUIRED",
    });
    instance = new S3Storage(client, bucket);
  } else {
    const root = process.env.PRIVATE_STORAGE_DIR || path.join(process.cwd(), ".private-storage");
    if (process.env.NODE_ENV === "production" && !process.env.PRIVATE_STORAGE_DIR) {
      // Inside the app directory it would be wiped by a fresh checkout. Warn loudly.
      console.warn("[private-storage] PRIVATE_STORAGE_DIR is not set; using", root);
    }
    instance = new LocalStorage(root);
  }
  return instance;
}
